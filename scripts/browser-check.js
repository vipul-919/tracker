import { chromium } from 'playwright-core';
import { MongoMemoryServer } from 'mongodb-memory-server';
import mongoose from 'mongoose';
import express from 'express';
import { mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createApp } from '../server/app.js';
import { dateKey } from '../shared/tracking.js';
const chrome = process.env.CHROME_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(p => existsSync(p));
if (!chrome) throw new Error('Set CHROME_PATH to an installed Chrome or Chromium executable.');
mkdirSync('.data/screenshots', { recursive: true });
let mongo, server, browser;
try {
  mongo = await MongoMemoryServer.create({ binary: { downloadDir: '.data/mongodb-binaries' } });
  await mongoose.connect(mongo.getUri());
  const app = createApp({ secret: 'browser-test-secret-at-least-32-characters' });
  app.use(express.static(path.resolve('dist')));
  server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
  browser = await chromium.launch({ executablePath: chrome, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
  page.setDefaultTimeout(15000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.getByRole('button', { name: 'Create an account', exact: true }).click();
  await page.getByLabel('Your name').fill('Alex Morgan');
  await page.getByLabel('Email address').fill('browser@example.com');
  await page.getByLabel('Password', { exact: true }).fill('test-browser-password');
  await page.getByRole('button', { name: 'Create your workspace', exact: true }).click();
  await page.getByRole('heading', { name: 'A clear view of your work.' }).waitFor();
  await page.getByRole('button', { name: /My Websites/ }).click();
  await page.getByRole('button', { name: 'Add website', exact: true }).first().click();
  await page.getByLabel('Website name').fill('Studio North');
  await page.getByLabel('Website URL').fill('https://studionorth.example');
  await page.getByLabel('Description', { exact: true }).fill('An independent design studio, made for thoughtful work.');
  await page.getByLabel('Project start date').fill(`${dateKey().slice(0, 4)}-01-01`);
  await page.getByRole('button', { name: 'Save website' }).click();
  await page.getByRole('heading', { name: 'Studio North', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Set target' }).click();
  await page.getByLabel('Allocated hours').fill('10');
  await page.getByRole('button', { name: 'Save monthly target' }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click();
  await page.getByRole('button', { name: 'Log work', exact: true }).first().click();
  await page.getByLabel('What did you work on?').fill('Designed a new homepage');
  await page.getByLabel('Hours', { exact: true }).fill('2');
  await page.getByLabel('Minutes', { exact: true }).fill('30');
  await page.getByRole('button', { name: 'Save work log' }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Work Logs', exact: true }).click();
  assert.equal(await page.locator('tbody tr').count(), 1);
  await page.getByTitle('Duplicate entry').click();
  await page.waitForFunction(() => document.querySelectorAll('tbody tr').length === 2);
  await page.getByTitle('Edit entry').first().click();
  await page.getByLabel('Minutes', { exact: true }).fill('45');
  await page.getByRole('button', { name: 'Save work log' }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.match(await page.locator('tbody').innerText(), /2h 45m/);
  await page.getByTitle('Delete entry').first().click();
  await page.getByRole('button', { name: 'Permanently delete' }).click();
  await page.waitForFunction(() => document.querySelectorAll('tbody tr').length === 1);
  await page.getByRole('button', { name: 'Calendar', exact: true }).click();
  assert.equal(await page.locator('.calendar-month').count(), 12);
  await page.locator('.calendar-day.today').click();
  assert.match(await page.getByRole('dialog').innerText(), /Designed a new homepage/);
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Month view' }).click();
  assert.equal(await page.locator('.calendar-month').count(), 1);
  await page.getByRole('button', { name: 'Reports', exact: true }).click();
  assert.match(await page.locator('.report-summary').innerText(), /2h 30m/);
  await page.getByLabel('Start date', { exact: true }).fill(`${dateKey().slice(0, 7)}-02`);
  assert.equal(await page.getByLabel('Start date', { exact: true }).inputValue(), `${dateKey().slice(0, 7)}-02`);
  const [csv] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'CSV', exact: true }).click()]);
  assert.equal(csv.suggestedFilename(), 'tempo-work-report.csv');
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click();
  assert.match(await page.locator('.completion-strip').innerText(), /25%/);
  // Additional sample projects exist only in this throwaway test database.
  await page.evaluate(async () => {
    const year = new Date().getFullYear(), month = `${year}-${String(new Date().getMonth() + 1).padStart(2, '0')}`;
    const projects = [['Forma Living', 'formaliving', 15, 8, 30], ['The Good Journal', 'goodjournal', 10, 6, 0], ['Olive & Oak', 'oliveandoak', 12, 13, 15], ['Fieldwork Studio', 'fieldwork', 8, 5, 45], ['Atlas Collective', 'atlascollective', 10, 7, 0]];
    for (const [name, host, target, hours, minutes] of projects) {
      const response = await fetch('/api/websites', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Requested-With': 'Tempo' }, body: JSON.stringify({ name, url: `https://${host}.example`, description: '', defaultMonthlyHours: target, startDate: `${year}-01-01`, status: 'Active' }) });
      const website = await response.json();
      await fetch('/api/logs', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Requested-With': 'Tempo' }, body: JSON.stringify({ websiteId: website.id, date: `${month}-03`, description: `${name} — design and development updates`, category: 'Development', hours, minutes, notes: '' }) });
    }
  });
  await page.reload();
  await page.waitForFunction(() => document.querySelectorAll('.progress-row').length === 6);
  await page.screenshot({ path: '.data/screenshots/dashboard-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Switch to dark mode' }).click();
  await page.screenshot({ path: '.data/screenshots/dashboard-dark.png', fullPage: true });
  await page.getByRole('button', { name: 'Switch to light mode' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 1 && document.documentElement.scrollWidth <= window.innerWidth);
  await page.screenshot({ path: '.data/screenshots/dashboard-mobile.png', fullPage: true });
  const overflow = await page.evaluate(() => ({ width: window.innerWidth, scroll: document.documentElement.scrollWidth, elements: [...document.querySelectorAll('body *')].filter(el => { const r = el.getBoundingClientRect(); return r.right > window.innerWidth + 1 && r.width > 0; }).map(el => ({ tag: el.tagName, class: String(el.className), width: el.getBoundingClientRect().width, right: el.getBoundingClientRect().right })).slice(0, 20) }));
  assert.equal(overflow.scroll <= overflow.width, true, `Mobile layout must not overflow: ${JSON.stringify(overflow)}`);
  await page.getByRole('button', { name: 'Open menu' }).click();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('heading', { name: 'Your workspace', exact: true }).waitFor();
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log('Browser checks passed: registration, websites, targets, work CRUD, duplicate, calendar, reports, CSV download, dashboard totals, dark mode, and mobile navigation. Screenshots: .data/screenshots/');
} finally {
  await browser?.close();
  if (server) await new Promise(resolve => server.close(resolve));
  await mongoose.disconnect(); await mongo?.stop();
}
